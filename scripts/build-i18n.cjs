// Generate a synchronous fallback catalog; no extra startup network requests.
const fs = require('node:fs');
function properties(name) {
    const out = {};
    for (const line of fs.readFileSync(name, 'utf8').split(/\r?\n/)) {
        const match = /^\s*([^#\s][^=]*?)\s*=\s*(.*)$/.exec(line);
        if (match) out[match[1].trim()] = match[2].replace(/\\u([0-9a-f]{4})/gi, (_, n) => String.fromCharCode(parseInt(n,16)));
    }
    return out;
}
const local = JSON.parse(fs.readFileSync('i18n/local-en.json', 'utf8'));
const data = { local, english: { ...properties('i18n/strings.txt'), ...properties('i18n/strings_en.txt') }, chinese: properties('i18n/strings_zh_CN.txt') };
fs.writeFileSync('js/local-i18n-catalog.js', '/* Generated by scripts/build-i18n.cjs. */\nwindow.FocusLocaleCatalog=' + JSON.stringify(data) + ';\n');
console.log('Generated English/local fallback catalog.');
